const params = new URLSearchParams(location.search);
let lang = params.get("lang") || (navigator.language || "en").slice(0, 2);
if (!I[lang]) lang = "en";

const TOKEN_KEY = "hestia.watch.token";
const POLL_MS = 5000;
let pollTimer = 0;
let inflight = false;
let runningCount = 0;
const healthCache = new Map();

function pack() {
  return I[lang] || I.en;
}

function applyLang() {
  document.documentElement.lang = lang;
  const p = pack();
  document.querySelectorAll("[data-i]").forEach((el) => {
    const key = el.getAttribute("data-i");
    if (p[key]) el.textContent = p[key];
  });
  document.querySelectorAll(".langs button").forEach((b) => {
    b.setAttribute("aria-pressed", b.dataset.lang === lang ? "true" : "false");
  });
}

function esc(value) {
  return String(value ?? "").replace(/[&<>"']/g, (ch) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  }[ch]));
}

function token() {
  return document.getElementById("token").value.trim();
}

function authHeaders() {
  const value = token();
  const headers = { Accept: "application/json" };
  if (value) headers.Authorization = `Bearer ${value}`;
  return headers;
}

function capId(row) {
  if (row.capability_id) return String(row.capability_id);
  const cap = row.capability;
  if (cap && typeof cap === "object" && cap.capability_id) return String(cap.capability_id);
  return "";
}

function publicUrl(row) {
  const raw = String(row.public_url || "");
  if (!raw) return "";
  try {
    const url = new URL(raw, location.origin);
    if (url.protocol !== "http:" && url.protocol !== "https:") return "";
    return url.toString().replace(/\/$/, "");
  } catch {
    return "";
  }
}

function invokeUrl(row) {
  const base = publicUrl(row);
  return base ? `${base}/invoke` : "";
}

function fmtTime(ts) {
  const n = Number(ts);
  if (!n) return pack().none;
  const date = new Date(n * 1000);
  if (Number.isNaN(date.getTime())) return pack().none;
  const locale = lang === "zh" ? "zh-CN" : lang;
  return date.toLocaleString(locale);
}

function setGateError(text) {
  const box = document.getElementById("gate-err");
  if (!text) {
    box.hidden = true;
    box.textContent = "";
    return;
  }
  box.hidden = false;
  box.textContent = text;
}

function lockWatch() {
  const gate = document.getElementById("gate");
  gate.hidden = false;
  gate.removeAttribute("aria-hidden");
  const cockpit = document.getElementById("cockpit");
  cockpit.hidden = true;
  cockpit.setAttribute("aria-hidden", "true");
  healthCache.clear();
  runningCount = 0;
}

function unlockWatch() {
  const gate = document.getElementById("gate");
  gate.hidden = true;
  gate.setAttribute("aria-hidden", "true");
  const cockpit = document.getElementById("cockpit");
  cockpit.hidden = false;
  cockpit.removeAttribute("aria-hidden");
  setGateError("");
}

async function readJson(res) {
  try {
    return await res.json();
  } catch {
    return {};
  }
}

async function probeHealth(slug, status) {
  if (status !== "running") return { state: "cold" };
  try {
    const res = await fetch(`/t/${encodeURIComponent(slug)}/health`);
    const body = await readJson(res);
    if (res.ok && body && body.ok === true) return { state: "live", code: res.status };
    return { state: "down", code: res.status };
  } catch {
    return { state: "down", code: 0 };
  }
}

function emberClass(status, health) {
  if (status !== "running") return "cold";
  if (health.state === "live") return "live";
  if (health.state === "down") return "down";
  return "cold";
}

function healthChip(health) {
  const p = pack();
  if (health.state === "live") return `<span class="chip ok">${esc(p.health_live)}</span>`;
  if (health.state === "down") {
    const code = health.code ? ` ${health.code}` : "";
    return `<span class="chip bad">${esc(p.health_down)}${esc(code)}</span>`;
  }
  if (health.state === "wait") return `<span class="chip dim">${esc(p.health_wait)}</span>`;
  return `<span class="chip dim">${esc(p.health_cold)}</span>`;
}

function renderEmpty() {
  const p = pack();
  document.getElementById("board").innerHTML =
    `<div class="empty"><strong>${esc(p.empty_t)}</strong><span>${esc(p.empty_p)}</span></div>`;
}

function renderBoard(rows, publicSlugs) {
  const p = pack();
  const board = document.getElementById("board");
  if (!rows.length) {
    renderEmpty();
    return;
  }
  board.innerHTML = rows
    .map((row) => {
      const slug = String(row.slug || "");
      const health = healthCache.get(slug) || { state: row.status === "running" ? "wait" : "cold" };
      const announced = Boolean(row.announced);
      const onHearth = publicSlugs.has(slug);
      const href = invokeUrl(row);
      const url = publicUrl(row);
      const error = String(row.last_error || "");
      const stopDisabled = row.status !== "running" ? "disabled" : "";
      return `<article class="coal" data-slug="${esc(slug)}">
        <div class="ember ${emberClass(row.status, health)}" aria-hidden="true"></div>
        <div class="meta">
          <h2>${esc(slug)}</h2>
          <div class="cap">${esc(capId(row) || p.none)}</div>
          <div class="chips">
            ${healthChip(health)}
            <span class="chip ${announced ? "ok" : "dim"}">${esc(announced ? p.announced : p.private)}</span>
            <span class="chip ${onHearth ? "ok" : "dim"}">${esc(onHearth ? p.on_hearth : p.off_hearth)}</span>
          </div>
          <div class="grid">
            <div>${esc(p.slug)} <b>${esc(slug)}</b></div>
            <div>${esc(p.status)} <b>${esc(row.status || p.none)}</b></div>
            <div>${esc(p.updated)} <b>${esc(fmtTime(row.updated_at))}</b></div>
            <div>URL <b>${esc(url || p.none)}</b></div>
          </div>
          ${error ? `<p class="last">${esc(p.err)}: ${esc(error)}</p>` : ""}
        </div>
        <div class="actions">
          ${href ? `<a href="${esc(href)}" target="_blank" rel="noopener">${esc(p.invoke)}</a>` : ""}
          <button type="button" class="tiny warn" data-stop="${esc(slug)}" ${stopDisabled}>${esc(p.stop)}</button>
        </div>
      </article>`;
    })
    .join("");
}

function paintOverview(body) {
  document.getElementById("n-running").textContent = String(body.running ?? 0);
  document.getElementById("n-stopped").textContent = String(body.stopped ?? 0);
  document.getElementById("n-tenants").textContent = String(body.tenants ?? 0);
  document.getElementById("n-hearth").textContent = body.hearth || pack().none;
  document.getElementById("n-runtime").textContent = body.runtime || pack().none;
  runningCount = Number(body.running || 0);
}

async function refresh() {
  if (inflight) return;
  const value = token();
  if (!value) {
    lockWatch();
    setGateError(pack().need);
    return;
  }
  inflight = true;
  const note = document.getElementById("board-note");
  try {
    const [overviewRes, tenantsRes, hearthRes] = await Promise.all([
      fetch("/v1/admin/overview", { headers: authHeaders() }),
      fetch("/v1/tenants", { headers: authHeaders() }),
      fetch("/v1/hearth"),
    ]);
    if (overviewRes.status === 401 || tenantsRes.status === 401) {
      sessionStorage.removeItem(TOKEN_KEY);
      lockWatch();
      setGateError(pack().denied);
      return;
    }
    if (!overviewRes.ok || !tenantsRes.ok) {
      note.textContent = pack().down;
      return;
    }
    const overview = await readJson(overviewRes);
    const tenantsBody = await readJson(tenantsRes);
    const hearthBody = hearthRes.ok ? await readJson(hearthRes) : { tenants: [] };
    note.textContent = "";
    unlockWatch();
    sessionStorage.setItem(TOKEN_KEY, value);
    paintOverview(overview);
    const rows = (Array.isArray(tenantsBody.tenants) ? tenantsBody.tenants : []).map((row) => {
      const copy = { ...row };
      delete copy.listen_url;
      return copy;
    });
    const publicSlugs = new Set(
      (Array.isArray(hearthBody.tenants) ? hearthBody.tenants : []).map((row) => row.slug)
    );
    rows.forEach((row) => {
      if (row.status !== "running") healthCache.set(row.slug, { state: "cold" });
    });
    renderBoard(rows, publicSlugs);
    const probes = rows.filter((row) => row.status === "running");
    await Promise.all(
      probes.map(async (row) => {
        const result = await probeHealth(row.slug, row.status);
        healthCache.set(row.slug, result);
      })
    );
    renderBoard(rows, publicSlugs);
  } catch {
    note.textContent = pack().down;
  } finally {
    inflight = false;
  }
}

function syncPoll() {
  clearInterval(pollTimer);
  if (document.getElementById("poll").checked && !document.getElementById("cockpit").hidden) {
    pollTimer = setInterval(() => {
      refresh().catch(() => {});
    }, POLL_MS);
  }
}

function mountAsh() {
  const canvas = document.getElementById("ash");
  const ctx = canvas.getContext("2d");
  if (!ctx) return;
  const sparks = Array.from({ length: 36 }, () => ({
    x: Math.random(),
    y: Math.random(),
    r: 0.4 + Math.random() * 1.6,
    s: 0.08 + Math.random() * 0.22,
    a: 0.15 + Math.random() * 0.45,
  }));
  function resize() {
    canvas.width = window.innerWidth;
    canvas.height = window.innerHeight;
  }
  resize();
  window.addEventListener("resize", resize);
  function tick() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    const heat = document.getElementById("cockpit").hidden ? 0.25 : 0.45 + Math.min(runningCount, 8) * 0.07;
    for (const spark of sparks) {
      spark.y -= spark.s * 0.004;
      if (spark.y < -0.02) {
        spark.y = 1.02;
        spark.x = Math.random();
      }
      ctx.beginPath();
      ctx.fillStyle = `rgba(255, 154, 60, ${spark.a * heat})`;
      ctx.arc(spark.x * canvas.width, spark.y * canvas.height, spark.r, 0, Math.PI * 2);
      ctx.fill();
    }
    requestAnimationFrame(tick);
  }
  tick();
}

document.getElementById("unlock").addEventListener("click", () => {
  refresh().then(syncPoll);
});
document.getElementById("token").addEventListener("keydown", (event) => {
  if (event.key === "Enter") refresh().then(syncPoll);
});
document.getElementById("refresh").addEventListener("click", () => {
  refresh().then(syncPoll);
});
document.getElementById("poll").addEventListener("change", syncPoll);
document.getElementById("board").addEventListener("click", async (event) => {
  const button = event.target.closest("[data-stop]");
  if (!button || button.disabled) return;
  const slug = button.getAttribute("data-stop");
  button.disabled = true;
  try {
    const res = await fetch(`/v1/tenants/${encodeURIComponent(slug)}/stop`, {
      method: "POST",
      headers: authHeaders(),
    });
    if (res.status === 401) {
      lockWatch();
      setGateError(pack().denied);
      return;
    }
    await refresh();
  } catch {
    document.getElementById("board-note").textContent = pack().down;
  }
});
document.querySelectorAll(".langs button").forEach((button) => {
  button.addEventListener("click", () => {
    lang = button.dataset.lang;
    applyLang();
    if (!document.getElementById("cockpit").hidden) refresh().catch(() => {});
  });
});

applyLang();
mountAsh();
const saved = sessionStorage.getItem(TOKEN_KEY);
if (saved) {
  document.getElementById("token").value = saved;
  refresh().then(syncPoll);
} else {
  lockWatch();
}
